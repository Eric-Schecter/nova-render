from pathlib import Path
from math import exp
from random import Random

size = 32
count = size * size
random = Random(121806)
kernel = [(x, y, exp(-(x*x+y*y) / (2*1.5**2))) for y in range(-6, 7) for x in range(-6, 7)]
seed = set(random.sample(range(count), count // 8))
energy = [0.] * count

def update(index, sign):
    x, y = index % size, index // size
    for dx, dy, weight in kernel:
        energy[((y+dy) % size)*size+(x+dx) % size] += sign * weight

def densest(mask):
    return max(mask, key=lambda i:(energy[i], -i))

def void(mask):
    return min((i for i in range(count) if i not in mask), key=lambda i:(energy[i], i))

for i in seed:
    update(i, 1)
for _ in range(count * 2):
    cluster = densest(seed)
    seed.remove(cluster)
    update(cluster, -1)
    empty = void(seed)
    seed.add(empty)
    update(empty, 1)
    if cluster == empty:
        break

prototype = energy[:]
ranks = [-1] * count
active = seed.copy()
for rank in range(len(seed)-1, -1, -1):
    i = densest(active)
    ranks[i] = rank
    active.remove(i)
    update(i, -1)
energy[:] = prototype
active = seed.copy()
for rank in range(len(seed), count//2):
    i = void(active)
    ranks[i] = rank
    active.add(i)
    update(i, 1)
active = set(range(count)) - active
energy[:] = [0.] * count
for i in active:
    update(i, 1)
for rank in range(count//2, count):
    i = densest(active)
    ranks[i] = rank
    active.remove(i)
    update(i, -1)
assert sorted(ranks) == list(range(count))
words = [(ranks[i] | (ranks[i+1] << 16)) for i in range(0, count, 2)]
text = '// Generated by scripts/generate-ao-blue-noise.py. Toroidal void-and-cluster ranks.\nstatic const uint novaBlueRank[512] = {\n'
for i in range(0, len(words), 8):
    text += '    '+', '.join(f'0x{word:08x}u' for word in words[i:i+8])+',\n'
text += '''};
float novaBluePhase(uint2 pixel, uint frame)
{
    uint index = (pixel.y & 31) * 32 + (pixel.x & 31);
    uint rank = (novaBlueRank[index / 2] >> ((index & 1) * 16)) & 1023;
    return frac((rank + .5) / 1024 + frame * .61803398875) * 6.28318531;
}
'''
(Path(__file__).resolve().parent.parent / "render/shaders/ao-blue-noise.hlsli").write_text(text)
